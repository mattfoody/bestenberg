#!/usr/bin/env node
/**
 * Writes every WordPress artifact derived from the component registry:
 *   wp/plugin/blocks/<type>/block.json            Bestenberg block types
 *   wp/plugin/generated/components.php            PHP runtime config
 *   wp/editor/src/blocks/manifest.ts              editor block registration list
 *   wp/plugin/tests/fixtures/style-classes.json   TS → PHP parity cases
 *   wp/plugin/tests/fixtures/adapter-page.html    markup of fixtures/adapter-page.json
 *
 * Run after building the packages: `pnpm generate`.
 */
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as prettier from 'prettier';
import {
  blockJson,
  CORE_META_ATTRIBUTE,
  coreComponents,
  docToMarkup,
  ownComponents,
  runtimeConfig,
} from '@bestenberg/adapter-blocks';
import {
  BREAKPOINTS,
  componentClasses,
  defaultRegistry,
  nodeClasses,
  sampleStyles,
  validateDoc,
} from '@bestenberg/schema';
import { phpReturnFile } from '@bestenberg/tokens';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');

async function pretty(file, source, parser) {
  const config = (await prettier.resolveConfig(file)) ?? {};
  return prettier.format(source, { ...config, parser });
}

async function write(path, contents) {
  const file = resolve(root, path);
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, contents);
  console.log(`  wrote ${path} (${Buffer.byteLength(contents)} bytes)`);
}

// 1. block.json per Bestenberg block (directory is fully generated).
const own = ownComponents(defaultRegistry);
await rm(resolve(root, 'wp/plugin/blocks'), { recursive: true, force: true });
for (const def of own) {
  const path = `wp/plugin/blocks/${def.type}/block.json`;
  await write(path, await pretty(resolve(root, path), JSON.stringify(blockJson(def)), 'json'));
}

// 2. PHP runtime config.
await write(
  'wp/plugin/generated/components.php',
  phpReturnFile(
    runtimeConfig(defaultRegistry),
    'Block runtime config: Bestenberg blocks and core blocks with Bestenberg styles.',
    'the component registry',
  ),
);

// 3. Editor manifest.
const manifestPath = 'wp/editor/src/blocks/manifest.ts';
const manifestDir = dirname(resolve(root, manifestPath));
const ident = (type) => type.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const manifest = [
  '// Generated by `pnpm generate` from the component registry. Do not edit.',
  ...own.map(
    (def) =>
      `import ${ident(def.type)} from '${relative(manifestDir, resolve(root, `wp/plugin/blocks/${def.type}/block.json`))}';`,
  ),
  '',
  '/** Bestenberg blocks: metadata and whether they hold inner blocks. */',
  'export const OWN_BLOCKS = [',
  ...own.map(
    (def) => `  { metadata: ${ident(def.type)}, container: ${def.allowedChildren !== 'none'} },`,
  ),
  '];',
  '',
  '/** Core blocks that carry the `bestenberg` attribute. */',
  `export const CORE_BLOCK_NAMES: readonly string[] = ${JSON.stringify(coreComponents(defaultRegistry).map((def) => def.block))};`,
  '',
  `export const CORE_META_ATTRIBUTE = ${JSON.stringify(CORE_META_ATTRIBUTE)};`,
  '',
].join('\n');
await write(manifestPath, await pretty(resolve(root, manifestPath), manifest, 'typescript'));

// 4. Parity fixtures: style/hidden → classes, computed in TypeScript.
const samples = sampleStyles();
const cases = [];
for (const style of samples) {
  cases.push({ style: { base: style } });
  cases.push({ style: { base: {}, tablet: style } });
  cases.push({ style: { base: {}, desktop: style } });
}
for (let mask = 1; mask < 8; mask++) {
  cases.push({
    hidden: Object.fromEntries(
      BREAKPOINTS.filter((_, i) => mask & (1 << i)).map((bp) => [bp, true]),
    ),
  });
}
cases.push({
  style: {
    base: {
      layout: { display: 'grid', columns: 1, gap: 'space.4' },
      padding: { x: 'space.4', y: 'space.8' },
    },
    tablet: { layout: { columns: 2 }, font: { size: 'fontSize.lg', align: 'center' } },
    desktop: {
      layout: { columns: 3, display: 'grid' },
      padding: { y: 'space.16' },
      border: { width: 0 },
    },
  },
  hidden: { tablet: true, base: false },
});
own.forEach((def, i) => {
  cases.push({
    block: def.block,
    style: {
      base: samples[(i * 7) % samples.length],
      desktop: samples[(i * 13 + 5) % samples.length],
    },
    hidden: i % 2 === 0 ? { desktop: true } : undefined,
  });
});
const withClasses = cases.map((c) => ({
  ...c,
  classes: c.block ? componentClasses(defaultRegistry.forBlock(c.block), c) : nodeClasses(c),
}));
await write(
  'wp/plugin/tests/fixtures/style-classes.json',
  `[\n${withClasses.map((c) => JSON.stringify(c)).join(',\n')}\n]\n`,
);

// 5. Adapter demo page markup (validated first).
const doc = JSON.parse(await readFile(resolve(here, '../fixtures/adapter-page.json'), 'utf8'));
const result = validateDoc(doc, { registry: defaultRegistry });
if (!result.ok) {
  throw new Error(
    `fixtures/adapter-page.json is invalid:\n${JSON.stringify(result.issues, null, 2)}`,
  );
}
await write('wp/plugin/tests/fixtures/adapter-page.html', `${docToMarkup(doc)}\n`);

console.log(`  ${own.length} Bestenberg blocks, ${withClasses.length} parity cases`);
