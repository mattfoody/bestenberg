<?php
/**
 * Bestenberg's own (dynamic) blocks.
 *
 * @package Bestenberg
 */

declare( strict_types=1 );

namespace Bestenberg\Blocks;

use Bestenberg\Styles\Collector;
use Bestenberg\Styles\StyleClasses;

/**
 * Registers the blocks in blocks/ (block.json generated from the component
 * registry) and renders them. Blocks store only attributes; markup is built
 * here at render time, so it can change without content migrations.
 *
 * @phpstan-type BlockConfig array{type: string, tag: string, tags: string[], classes: string[], attributes: array<string, string>, container: bool}
 */
final class LayoutBlocks {

	public const EDITOR_SCRIPT = 'bestenberg-blocks';

	/**
	 * Constructor.
	 *
	 * @param array<string, BlockConfig> $blocks        Block name => runtime config.
	 * @param StyleClasses               $style_classes Style mapper.
	 * @param Collector                  $collector     Request class collector.
	 */
	public function __construct(
		private array $blocks,
		private StyleClasses $style_classes,
		private Collector $collector
	) {}

	/**
	 * Generated runtime config (generated/components.php).
	 *
	 * @return array{blocks: array<string, BlockConfig>, core: array<string, array{type: string, target: string|null}>}
	 */
	public static function config(): array {
		/**
		 * Generated config.
		 *
		 * @var array{blocks: array<string, BlockConfig>, core: array<string, array{type: string, target: string|null}>} $config
		 */
		$config = require BESTENBERG_DIR . 'generated/components.php';
		return $config;
	}

	/**
	 * Registers hooks.
	 */
	public function register(): void {
		add_action( 'init', array( $this, 'register_blocks' ) );
	}

	/**
	 * Registers the editor script and every block type.
	 */
	public function register_blocks(): void {
		$this->register_editor_script();

		foreach ( $this->blocks as $name => $block ) {
			$dir = BESTENBERG_DIR . 'blocks/' . $block['type'];
			if ( ! is_readable( $dir . '/block.json' ) || \WP_Block_Type_Registry::get_instance()->is_registered( $name ) ) {
				continue;
			}
			register_block_type( $dir, array( 'render_callback' => array( $this, 'render' ) ) );
		}
	}

	/**
	 * Script that registers the blocks (and core block metadata) in the editor.
	 */
	private function register_editor_script(): void {
		$asset_file = BESTENBERG_DIR . 'build/editor/blocks.asset.php';
		if ( ! is_readable( $asset_file ) || wp_script_is( self::EDITOR_SCRIPT, 'registered' ) ) {
			return;
		}
		/**
		 * Asset metadata generated by @wordpress/scripts.
		 *
		 * @var array{dependencies: string[], version: string} $asset
		 */
		$asset = require $asset_file;
		wp_register_script(
			self::EDITOR_SCRIPT,
			BESTENBERG_URL . 'build/editor/blocks.js',
			$asset['dependencies'],
			$asset['version'],
			array( 'in_footer' => true )
		);
	}

	/**
	 * All classes for a block: element classes, then utilities. Mirrors
	 * componentClasses() in @bestenberg/schema.
	 *
	 * @param string $name   Block name.
	 * @param mixed  $style  Responsive style attribute.
	 * @param mixed  $hidden Visibility attribute.
	 * @return string[]
	 */
	public function classes( string $name, mixed $style, mixed $hidden ): array {
		$base = $this->blocks[ $name ]['classes'] ?? array();
		return array_values( array_unique( array_merge( $base, $this->style_classes->for_node( $style, $hidden ) ) ) );
	}

	/**
	 * Render callback.
	 *
	 * @param array<string, mixed> $attributes Block attributes.
	 * @param string               $content    Rendered inner blocks.
	 * @param \WP_Block            $block      Block instance.
	 */
	public function render( array $attributes, string $content, \WP_Block $block ): string {
		$config = $this->blocks[ $block->name ] ?? null;
		if ( null === $config ) {
			return $content;
		}

		$props = is_array( $attributes['props'] ?? null ) ? $attributes['props'] : array();

		$tag = $config['tag'];
		if ( isset( $props['tag'] ) && in_array( $props['tag'], $config['tags'], true ) ) {
			$tag = $props['tag'];
		}

		$classes = $this->classes( $block->name, $attributes['style'] ?? null, $attributes['hidden'] ?? null );
		$this->collector->record( $classes );

		$extra = array( 'class' => implode( ' ', $classes ) );
		if ( isset( $props['anchor'] ) && is_string( $props['anchor'] ) && 1 === preg_match( '/^[A-Za-z][\w-]*$/', $props['anchor'] ) ) {
			$extra['id'] = $props['anchor'];
		}
		foreach ( $config['attributes'] as $attribute => $value ) {
			$extra[ $attribute ] = $value;
		}

		return sprintf(
			'<%1$s %2$s>%3$s</%1$s>',
			$tag,
			get_block_wrapper_attributes( $extra ),
			$config['container'] ? $content : ''
		);
	}
}
